/* Dev & Deploy tab: the development, database, deployment and CI/CD guides plus
   the AI prompt library, served from this instance so the in-house team can read
   and download them without leaving the dashboard.

   Everything is rendered with the markdown helpers already defined in
   index.html (parseMdBlocks / MdBlocks), so no markdown library is added and
   there is still no build step. Loaded before index.html's inline script. */

const DEV_KIT_DOCS_URL = "/api/docs/dev-kit";
const DEV_KIT_BUNDLE_URL = "/api/docs/dev-kit/bundle";
const DEV_KIT_GITHUB_URL = "https://github.com/Raheelatta1984/testforge/tree/main/docs";

/* Split a guide into a title, the text before the first `##` and one section per
   `##` heading. Fenced code blocks are respected: a shell script inside the
   guide can contain a line that starts with `##` and must not become a section. */
function devKitSplit(markdown) {
  let title = "";
  const intro = [];
  const sections = [];
  let current = null;
  let inFence = false;
  for (const line of String(markdown || "").split("\n")) {
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
      (current ? current.lines : intro).push(line);
      continue;
    }
    if (!inFence) {
      const h2 = /^##\s+(.*)$/.exec(line);
      const h1 = /^#\s+(.*)$/.exec(line);
      if (h2) { current = { title: h2[1].trim(), lines: [] }; sections.push(current); continue; }
      if (h1 && !title) { title = h1[1].trim(); continue; }
    }
    (current ? current.lines : intro).push(line);
  }
  return {
    title,
    intro: intro.join("\n"),
    sections: sections.map(section => ({ title: section.title, markdown: section.lines.join("\n") })),
  };
}

/* Clipboard with a fallback: the dashboard is served over http on a local host,
   where navigator.clipboard is not available in every browser. */
function devKitCopy(text) {
  if (navigator.clipboard && navigator.clipboard.writeText) {
    return navigator.clipboard.writeText(text).then(() => true, () => false);
  }
  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(area);
    return Promise.resolve(ok);
  } catch (_) {
    return Promise.resolve(false);
  }
}

function DevKitDocView({ doc, done, toggleDone }) {
  const [open, setOpen] = useState({ 0: true });
  const [copied, setCopied] = useState(false);
  if (!doc) return e("p", { className: "text-xs text-slate-400" }, "Choose a guide on the left.");
  const parsed = devKitSplit(doc.markdown);
  const total = parsed.sections.length || 1;
  const ticked = parsed.sections.filter((_, index) => done[index]).length;
  const percent = Math.round((ticked / total) * 100);

  return e("div", { className: "space-y-3" },
    e("div", { className: "bg-slate-900 border border-slate-800 rounded-2xl p-4 space-y-2" },
      e("div", { className: "flex flex-wrap items-start justify-between gap-2" },
        e("div", { className: "min-w-0" },
          e("h3", { className: "text-sm font-bold text-indigo-200" }, parsed.title || doc.title),
          e("p", { className: "text-[11px] text-slate-400 mt-1" }, doc.blurb),
          e("p", { className: "text-[9px] font-mono text-slate-500 mt-1 break-all" },
            (doc.path || "generated by app/dev_prompts.py") + " · " + Math.round((doc.bytes || 0) / 1024) + " KB")),
        e("div", { className: "flex flex-wrap gap-2 shrink-0" },
          e("button", { type: "button", className: "key-btn",
            onClick: () => devKitCopy(doc.markdown).then(ok => { setCopied(ok); setTimeout(() => setCopied(false), 2000); }) },
            copied ? "COPIED ✓" : "COPY MARKDOWN"),
          e("a", { href: DEV_KIT_DOCS_URL + "/" + doc.slug + "/download",
            className: "key-btn text-indigo-200 no-underline" }, "DOWNLOAD .MD"))),
      doc.truncated && e("p", { role: "status", className: "text-[11px] text-amber-300" },
        "This guide is larger than the server is willing to serve and was cut short. Download it for the full text."),
      parsed.sections.length > 0 && e("div", { className: "space-y-1 pt-1" },
        e("div", { className: "h-2 bg-slate-800 rounded-full overflow-hidden" },
          e("div", { className: "h-full bg-indigo-500 transition-all", style: { width: percent + "%" } })),
        e("div", { className: "flex justify-between items-center" },
          e("span", { className: "text-[10px] text-slate-400" }, ticked + " of " + total + " sections ticked"),
          e("button", { type: "button",
            className: "text-[9px] font-bold px-2 py-1 rounded bg-slate-800 hover:bg-indigo-700",
            onClick: () => setOpen(parsed.sections.reduce((all, _s, index) => ({ ...all, [index]: !open[index] }), {})) },
            "TOGGLE ALL SECTIONS")))),
    parsed.intro.trim() && e("div", { className: "bg-slate-900 border border-slate-800 rounded-2xl p-4" },
      e(MdBlocks, { blocks: parseMdBlocks(parsed.intro) })),
    parsed.sections.map((section, index) => {
      const isOpen = !!open[index];
      const isDone = !!done[index];
      return e("div", { key: index, className: "bg-slate-900 border rounded-2xl overflow-hidden " +
        (isDone ? "border-emerald-800/60" : "border-slate-800") },
        e("div", { className: "flex items-stretch" },
          e("button", { type: "button", title: isDone ? "Mark as not read" : "Mark as read",
            onClick: () => toggleDone(index),
            className: "px-3 text-lg " + (isDone ? "text-emerald-400" : "text-slate-600 hover:text-slate-400") },
            isDone ? "✅" : "⬜"),
          e("button", { type: "button", className: "flex-1 text-left p-3 pl-1",
            onClick: () => setOpen(prev => ({ ...prev, [index]: !isOpen })) },
            e("div", { className: "flex justify-between items-center gap-2" },
              e("span", { className: "font-bold text-xs " + (isDone ? "text-emerald-300" : "text-slate-200") },
                section.title),
              e("span", { className: "text-slate-500 text-xs" }, isOpen ? "▲" : "▼")))),
        isOpen && e("div", { className: "p-4 pt-1 border-t border-slate-800/70" },
          e(MdBlocks, { blocks: parseMdBlocks(section.markdown) })));
    }));
}

function DevKitPromptCard({ prompt, phaseName }) {
  const [copied, setCopied] = useState(false);
  const copy = () => devKitCopy(prompt.prompt).then(ok => { setCopied(ok); setTimeout(() => setCopied(false), 2000); });
  return e("article", { className: "bg-slate-900 border border-slate-800 rounded-2xl p-4 space-y-2" },
    e("div", { className: "flex flex-wrap justify-between items-start gap-2" },
      e("div", { className: "min-w-0" },
        e("h4", { className: "text-xs font-bold text-indigo-200" }, prompt.title),
        e("p", { className: "text-[10px] text-slate-500 mt-0.5 font-mono" }, phaseName + " · " + prompt.id)),
      e("button", { type: "button", className: "key-btn shrink-0", onClick: copy }, copied ? "COPIED ✓" : "COPY PROMPT")),
    e("p", { className: "text-[11px] text-slate-300" }, e("b", { className: "text-slate-400" }, "Use it when: "), prompt.when),
    e("div", { className: "text-[11px] text-slate-300" },
      e("b", { className: "text-slate-400" }, "Paste these inputs too:"),
      e("ul", { className: "list-disc pl-4 mt-1 space-y-0.5 text-slate-400" },
        (prompt.inputs || []).map((item, index) => e("li", { key: index }, item)))),
    e("pre", { className: "text-[10px] leading-relaxed whitespace-pre-wrap bg-slate-950 border border-slate-800 rounded-xl p-3 text-slate-200" },
      prompt.prompt),
    e("p", { className: "text-[11px] text-slate-300" }, e("b", { className: "text-slate-400" }, "You should get back: "), prompt.output),
    (prompt.review || []).length > 0 && e("div", { className: "text-[11px]" },
      e("b", { className: "text-slate-400" }, "Before you accept it:"),
      e("ul", { className: "list-none pl-0 mt-1 space-y-0.5 text-emerald-200/90" },
        prompt.review.map((check, index) => e("li", { key: index }, "☐ " + check)))));
}

function DevDeployTab({ setTab }) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [view, setView] = useState("docs");
  const [slug, setSlug] = useState("architecture");
  const [active, setActive] = useState(null);
  const [phase, setPhase] = useState("all");
  // Reading progress stays on this device only, one entry per document.
  const [done, setDone] = useState(() => {
    try { return JSON.parse(localStorage.getItem("tf_devkit_done") || "{}"); } catch (_) { return {}; }
  });

  useEffect(() => {
    let stop = false;
    API.get("/api/dev/kit")
      .then(res => { if (!stop) { setData(res); setError(""); } })
      .catch(err => { if (!stop) setError(err.message); })
      .finally(() => { if (!stop) setLoading(false); });
    return () => { stop = true; };
  }, []);

  useEffect(() => {
    if (!data) return undefined;
    let stop = false;
    setLoading(true);
    API.get(DEV_KIT_DOCS_URL + "/" + slug)
      .then(doc => { if (!stop) setActive(doc); })
      .catch(err => { if (!stop) setError(err.message); })
      .finally(() => { if (!stop) setLoading(false); });
    return () => { stop = true; };
  }, [slug, data]);

  const docs = (data && data.docs) || [];
  const docProgress = done[slug] || {};
  const toggleDone = (index) => {
    setDone(prev => {
      const current = { ...(prev[slug] || {}) };
      if (current[index]) delete current[index]; else current[index] = true;
      const next = { ...prev, [slug]: current };
      try { localStorage.setItem("tf_devkit_done", JSON.stringify(next)); } catch (_) {}
      return next;
    });
  };
  const prompts = (data && data.prompts) || [];
  const phases = (data && data.phases) || [];
  const shown = phase === "all" ? prompts : prompts.filter(item => item.phase === phase);
  const phaseName = (id) => (phases.find(item => item.id === id) || {}).name || id;

  return e("div", { className: "space-y-4" },
    e(GuideSection, { id: "devkit-intro", label: "Dev & Deploy kit",
      action: "Read the guides in order, copy a prompt for the AI assistant, then download the pack for the team." },
    e("section", { className: "bg-slate-900 p-5 rounded-3xl border border-slate-800 space-y-4" },
      e("div", { className: "flex flex-wrap justify-between items-start gap-2" },
        e("div", { className: "min-w-0" },
          e("h2", { className: "font-bold text-lg text-indigo-300" }, "Development & deployment kit 🛠️"),
          e("p", { className: "text-xs text-slate-400 mt-1" },
            "The end-to-end story for building and shipping this service: the codebase map, local setup, " +
            "SQL Server on Azure, deployment, CI/CD and the AI prompt library. Served from this instance, " +
            "downloadable as markdown, and safe to hand to the in-house dev team.")),
        e("div", { className: "flex flex-wrap gap-2 shrink-0" },
          e("a", { href: DEV_KIT_BUNDLE_URL, className: "key-btn text-indigo-200 no-underline" }, "⬇ DOWNLOAD ALL (.ZIP)"),
          e("a", { href: DEV_KIT_GITHUB_URL, target: "_blank", rel: "noopener noreferrer",
            className: "key-btn text-indigo-200 no-underline" }, "📖 DOCS ON GITHUB ↗"))),
      e("div", { className: "flex flex-wrap gap-2" },
        [["docs", "📘 Guides (" + docs.length + ")"], ["prompts", "🤖 AI prompts (" + prompts.length + ")"]]
          .map(([key, label]) => e("button", { key, type: "button", onClick: () => setView(key),
            className: "px-3 py-2 rounded-xl text-[11px] font-bold border " +
              (view === key ? "bg-indigo-700 border-indigo-500 text-white" : "bg-slate-950 border-slate-700 text-slate-300") },
            label)))),
      loading && e("p", { className: "text-sm text-slate-400" }, "Loading the kit…"),
      error && e("div", { role: "alert", className: "bg-red-950/40 border border-red-800/40 text-red-200 p-4 rounded-2xl space-y-2" },
        e("p", { className: "text-sm font-bold" }, "The Dev & Deploy kit could not be loaded."),
        e("p", { className: "text-xs" }, error),
        e("a", { href: DEV_KIT_GITHUB_URL, target: "_blank", rel: "noopener noreferrer",
          className: "block text-center bg-slate-800 text-indigo-300 text-xs font-bold px-4 py-2 rounded-xl underline" },
          "Read the guides on GitHub instead")),

      view === "docs" && e("div", { className: "grid grid-cols-1 lg:grid-cols-[minmax(200px,280px)_minmax(0,1fr)] gap-3" },
        e("nav", { "aria-label": "Dev and deploy guides", className: "space-y-2 min-w-0" },
          docs.map(item => {
            const ticked = Object.keys(done[item.slug] || {}).length;
            const isSelected = item.slug === slug;
            return e("button", { key: item.slug, type: "button", onClick: () => setSlug(item.slug),
              className: "w-full text-left rounded-xl border p-3 space-y-1 " +
                (isSelected ? "bg-indigo-950/60 border-indigo-600" : "bg-slate-950 border-slate-800 hover:border-slate-600") },
              e("div", { className: "flex justify-between gap-2 items-start" },
                e("span", { className: "text-xs font-bold " + (isSelected ? "text-indigo-200" : "text-slate-200") }, item.title),
                e("span", { className: "text-[9px] text-slate-500 shrink-0" },
                  item.generated ? "generated" : Math.round((item.bytes || 0) / 1024) + " KB")),
              e("p", { className: "text-[10px] text-slate-400" }, item.blurb),
              e("p", { className: "text-[9px] text-slate-500" },
                item.audience + (ticked ? " · " + ticked + " read" : "")),
              !item.available && e("p", { className: "text-[9px] text-amber-300" }, "Not in this deployment"));
          })),
        e("div", { className: "min-w-0" },
          view === "docs" && e(DevKitDocView, { doc: active, done: docProgress, toggleDone }))),

      view === "prompts" && e("div", { className: "space-y-3" },
        e("div", { className: "bg-slate-950 border border-slate-800 rounded-2xl p-3 space-y-2" },
          e("p", { className: "text-[11px] text-slate-300" },
            "Copy a prompt, replace every <ANGLE BRACKET PLACEHOLDER>, and paste the inputs it lists into the " +
            "same message. An answer about code the assistant has not seen is a guess. The downloadable " +
            "ai-prompt-library.md is generated from the same list, so the file you email cannot drift from this tab."),
          e("div", { className: "flex flex-wrap gap-1.5" },
            [["all", "All phases"]].concat(phases.map(item => [item.id, item.name])).map(([key, label]) =>
              e("button", { key, type: "button", onClick: () => setPhase(key),
                className: "text-[9px] font-bold px-2 py-1 rounded-full border " +
                  (phase === key ? "bg-indigo-700 border-indigo-500 text-white" : "bg-slate-900 border-slate-700 text-slate-300") },
                label)))),
        e("div", { className: "grid grid-cols-1 xl:grid-cols-2 gap-3" },
          shown.map(prompt => e(DevKitPromptCard, { key: prompt.id, prompt, phaseName: phaseName(prompt.phase) })))),

      e("div", { className: "bg-slate-950 border border-sky-900 rounded-2xl p-4 space-y-2" },
        e("h3", { className: "text-sm font-bold text-sky-300" }, "Handing this to the in-house dev team"),
        e("ul", { className: "list-disc pl-4 space-y-1 text-[11px] text-slate-300" },
          e("li", {}, "Send the zip: one file, seven markdown documents, no credentials in any of them."),
          e("li", {}, "Or point them at this tab — it is the same text the repository serves, so it cannot go stale."),
          e("li", {}, "Start with Architecture, then Local setup; the SQL guide is the one to read before touching a database."),
          e("li", {}, "The Windows Desktop tab installs a custom desktop application before recording it; the " +
            "SQL guide covers the database that stores what the recording produced."))),
      e("div", { className: "flex flex-wrap gap-2" },
        e("button", { type: "button", onClick: () => setTab && setTab("azure"), className: "key-btn" }, "OPEN AZURE TAB"),
        e("button", { type: "button", onClick: () => setTab && setTab("desktop-record"), className: "key-btn" },
          "OPEN WINDOWS DESKTOP"),
        e("button", { type: "button", onClick: () => setTab && setTab("logs"), className: "key-btn" }, "OPEN LOGS")),
      e("p", { className: "text-[10px] text-slate-500" },
        "Guides are read from docs/ in this deployment and rendered here; the AI prompt library is generated " +
        "from app/dev_prompts.py. Anything marked [verify] depends on a quota, a price or a vendor limit — " +
        "check it against your own subscription before relying on it."))
  );
}

window.DevDeployTab = DevDeployTab;
